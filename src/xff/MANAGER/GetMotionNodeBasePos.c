static inline void vecAddXYZ(float *out, float *a, float *b)
{
    __asm__ __volatile__("lqc2 vf5, 0x0(%1)\n"
                         "lqc2 vf6, 0x0(%2)\n"
                         "vadd.xyz vf5, vf5, vf6\n"
                         "sqc2 vf5, 0x0(%0)\n"
                         : : "r"(out), "r"(a), "r"(b) : "memory");
}

void GetMotionNodeBasePos(float *out, Motion *motion, char *quats, int node)
{
    *(s128 *)out = ZeroPoint;
    while (node != -1) {
        quatRotate(out, (float *)(quats + node * 0x10), out);
        vecAddXYZ(out, out, motion->nodes[node].pos);
        node = motion->nodes[node].parent;
    }
}
