void GAMEUTIL_get_xyz_axis_from_quaternion(float *x, float *y, float *z, float *q)
{
    __asm__ __volatile__("lqc2 vf04, 0x0(%1)\n"
                         "vmul.xyzw vf05, vf04, vf04\n"
                         "vmr32.xyzw vf06, vf04\n"
                         "vmul.xyzw vf07, vf06, vf04\n"
                         "vmr32.xyzw vf06, vf06\n"
                         "vmul.xyzw vf08, vf06, vf04\n"
                         "vsubz.x vf06, vf07, vf07z\n"
                         "vaddx.y vf06, vf00, vf06x\n"
                         "vsuby.x vf06, vf00, vf05y\n"
                         "vsubz.x vf06, vf06, vf05z\n"
                         "vaddw.z vf06, vf08, vf08w\n"
                         "vsub.w vf06, vf06, vf06\n"
                         "vsub.w vf06, vf00, vf00\n"
                         "vadd.w vf05, vf00, vf00\n"
                         "vmulw.xyz vf06, vf06, vf05w\n"
                         "vaddw.x vf06, vf06, vf00w\n"
                         "sqc2 vf06, 0x0(%0)\n"
                         : : "r"(x), "r"(q) : "memory");
    __asm__ __volatile__("lqc2 vf04, 0x0(%1)\n"
                         "vmul.xyzw vf05, vf04, vf04\n"
                         "vmr32.xyzw vf06, vf04\n"
                         "vmul.xyzw vf07, vf06, vf04\n"
                         "vaddy.z vf06, vf00, vf07y\n"
                         "vsubw.z vf06, vf06, vf07w\n"
                         "vsubx.y vf06, vf00, vf05x\n"
                         "vsubz.y vf06, vf06, vf05z\n"
                         "vaddz.x vf06, vf07, vf07z\n"
                         "vsub.w vf06, vf00, vf00\n"
                         "vadd.w vf05, vf00, vf00\n"
                         "vmulw.xyz vf06, vf06, vf05w\n"
                         "vaddw.y vf06, vf06, vf00w\n"
                         "sqc2 vf06, 0x0(%0)\n"
                         : : "r"(y), "r"(q) : "memory");
    __asm__ __volatile__("lqc2 vf04, 0x0(%1)\n"
                         "vmul.xyzw vf05, vf04, vf04\n"
                         "vmr32.xyzw vf06, vf04\n"
                         "vmul.xyzw vf07, vf06, vf04\n"
                         "vmr32.xyzw vf06, vf06\n"
                         "vmul.xyzw vf08, vf06, vf04\n"
                         "vsubx.z vf06, vf00, vf05x\n"
                         "vsuby.z vf06, vf06, vf05y\n"
                         "vaddw.y vf06, vf07, vf07w\n"
                         "vsuby.x vf06, vf08, vf08y\n"
                         "vsub.w vf06, vf00, vf00\n"
                         "vadd.w vf05, vf00, vf00\n"
                         "vmulw.xyz vf06, vf06, vf05w\n"
                         "vaddw.z vf06, vf06, vf00w\n"
                         "sqc2 vf06, 0x0(%0)\n"
                         ".set noreorder\n"
                         ".set reorder\n"
                         : : "r"(z), "r"(q) : "memory");
}
