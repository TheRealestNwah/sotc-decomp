void iosInverseMatrix(float *out, float *in)
{
    __asm__ __volatile__("lq $8, 0x0(%1)\n"
                         "lq $9, 0x10(%1)\n"
                         "lq $10, 0x20(%1)\n"
                         "lqc2 vf1, 0x30(%1)\n"
                         "vmove.xyzw vf2, vf1\n"
                         "vsub.xyz vf1, vf1, vf1\n"
                         "vmove.xyzw vf9, vf1\n"
                         "qmfc2 $11, vf1\n"
                         "pextlw $12, $9, $8\n"
                         "pextuw $13, $9, $8\n"
                         "pextlw $14, $11, $10\n"
                         "pextuw $15, $11, $10\n"
                         "pcpyld $8, $14, $12\n"
                         "pcpyud $9, $12, $14\n"
                         "pcpyld $10, $15, $13\n"
                         "qmtc2 $8, vf3\n"
                         "qmtc2 $9, vf4\n"
                         "qmtc2 $10, vf8\n"
                         "vmulax.xyz ACC, vf3, vf2x\n"
                         "vmadday.xyz ACC, vf4, vf2y\n"
                         "vmaddz.xyz vf1, vf8, vf2z\n"
                         "vsub.xyz vf1, vf9, vf1\n"
                         "sq $8, 0x0(%0)\n"
                         "sq $9, 0x10(%0)\n"
                         "sq $10, 0x20(%0)\n"
                         "sqc2 vf1, 0x30(%0)\n"
                         ".set noreorder\n.set reorder\n"
                         : : "r"(out), "r"(in) : "$8", "$9", "$10", "$11", "$12", "$13", "$14", "$15", "memory");
}
