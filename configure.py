"""Generate build.ninja for rebuilding the loader ELF from splat's assembly.

    python configure.py            # split (if needed) and write build.ninja
    python configure.py --split    # force a fresh split first
    ninja                          # assemble + link + flatten
    ninja check                    # compare the rebuilt image to the original

The EE binutils prefix defaults to `mips64r5900el-ps2-elf-` (PS2DEV) and can
be overridden with --cross or the SOTC_CROSS environment variable.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BASENAME = "SCUS_974.72"
SPLAT_CONFIG = f"{BASENAME}.yaml"
BASE_ELF = f"iso/{BASENAME}"
BASE_ROM = f"iso/{BASENAME}.rom"
BUILD_DIR = "build"
DEFAULT_CROSS = "mips64r5900el-ps2-elf-"
CROSS_CANDIDATES = [
    DEFAULT_CROSS,
    "mips64r5900el-linux-gnu-",
    "mips-linux-gnu-",
    "mipsel-linux-gnu-",
]

ASFLAGS = "-EL -march=r5900 -mabi=eabi -G 0 -no-pad-sections -I include"
# Modern PS2DEV ld defaults to n32; the original (and our objects) are EABI.
LDFLAGS = "-m elf32lr5900"
LD_SCRIPTS = [
    "undefined_syms_auto.txt",
    "undefined_funcs_auto.txt",
    f"{BASENAME}.ld",
    "linker_script_extra.ld",
]


def find_cross(requested: str | None) -> str:
    if requested:
        return requested
    for prefix in CROSS_CANDIDATES:
        if shutil.which(prefix + "as"):
            return prefix
    return DEFAULT_CROSS


def ninja_path(path: Path | str) -> str:
    """Forward slashes, with ninja's special characters escaped."""
    return str(path).replace("\\", "/").replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def run_split() -> None:
    if not (ROOT / BASE_ROM).is_file():
        subprocess.run(
            [sys.executable, "tools/elf2rom.py", BASE_ELF, BASE_ROM], cwd=ROOT, check=True
        )
    subprocess.run([sys.executable, "-m", "splat", "split", SPLAT_CONFIG], cwd=ROOT, check=True)


def asm_sources() -> list[Path]:
    return sorted(p.relative_to(ROOT) for p in (ROOT / "asm").rglob("*.s"))


def object_for(source: Path) -> Path:
    # Matches the paths splat writes into the linker script (o_as_suffix: build/asm/x.o).
    return Path(BUILD_DIR) / source.with_suffix(".o")


def generate(cross: str, sources: list[Path]) -> str:
    python = f'"{sys.executable}"'.replace("$", "$$")
    elf = f"{BUILD_DIR}/{BASENAME}.elf"
    rom = f"{BUILD_DIR}/{BASENAME}.rom"
    objects = [ninja_path(object_for(s)) for s in sources]
    ld_scripts = " ".join(f"-T {s}" for s in LD_SCRIPTS)

    lines = [
        "# Generated by configure.py. Do not edit.",
        f"cross = {cross}",
        f"asflags = {ASFLAGS}",
        f"python = {python}",
        "",
        "rule as",
        "  command = ${cross}as $asflags -o $out $in",
        "  description = AS $in",
        "",
        "rule ld",
        f"  command = ${{cross}}ld {LDFLAGS} {ld_scripts} -Map {BUILD_DIR}/{BASENAME}.map"
        " --no-check-sections -o $out",
        "  description = LD $out",
        "",
        "rule flatten",
        "  command = $python tools/elf2rom.py $in $out",
        "  description = FLATTEN $out",
        "",
        "rule check",
        "  command = $python tools/check.py $in",
        "  description = CHECK",
        "",
        "rule configure",
        "  command = $python configure.py --cross $cross",
        "  generator = 1",
        "",
        f"build build.ninja: configure configure.py {SPLAT_CONFIG}",
        "",
    ]
    for source, obj in zip(sources, objects, strict=True):
        lines.append(f"build {obj}: as {ninja_path(source)} | include/macro.inc")
    lines += [
        "",
        f"build {elf}: ld | {' '.join(objects)} {' '.join(LD_SCRIPTS)}",
        f"build {rom}: flatten {elf}",
        f"build {BASE_ROM}: flatten {BASE_ELF}",
        f"build check: check {rom} {BASE_ROM}",
        "",
        f"default {rom}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--split", action="store_true", help="re-run splat before generating")
    parser.add_argument("--cross", default=os.environ.get("SOTC_CROSS"), help="binutils prefix")
    args = parser.parse_args(argv)

    if not (ROOT / BASE_ELF).is_file():
        print(f"Missing {BASE_ELF}. Copy it from your own disc first.", file=sys.stderr)
        return 1
    if args.split or not (ROOT / "asm").is_dir():
        run_split()

    cross = find_cross(args.cross)
    if not shutil.which(cross + "as"):
        print(f"warning: {cross}as not found on PATH; `ninja` will fail until it's installed.")

    (ROOT / "build.ninja").write_text(generate(cross, asm_sources()), encoding="utf-8")
    print(f"Wrote build.ninja (cross = {cross})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
