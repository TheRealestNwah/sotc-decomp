"""Generate build.ninja for rebuilding the loader ELF from splat's assembly.

    python configure.py            # split (if needed) and write build.ninja
    python configure.py --split    # force a fresh split first
    ninja                          # assemble + link + flatten
    ninja check                    # compare the rebuilt image to the original

The EE binutils prefix defaults to `mips64r5900el-ps2-elf-` (PS2DEV) and can
be overridden with --cross or the SOTC_CROSS environment variable.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BASENAME = "SCUS_974.72"
SPLAT_CONFIG = f"{BASENAME}.yaml"
BASE_ELF = f"iso/{BASENAME}"
BASE_ROM = f"iso/{BASENAME}.rom"
BUILD_DIR = "build"
DEFAULT_CROSS = "mips64r5900el-ps2-elf-"
CROSS_CANDIDATES = [
    DEFAULT_CROSS,
    "mips64r5900el-linux-gnu-",
    "mips-linux-gnu-",
    "mipsel-linux-gnu-",
]

ASFLAGS = "-EL -march=r5900 -mabi=eabi -G 0 -no-pad-sections -I include"
# Modern PS2DEV ld defaults to n32; the original (and our objects) are EABI.
LDFLAGS = "-m elf32lr5900"
XFF_MODULES = ["KERNEL", "MANAGER", "GAMECORE"]
LD_SCRIPTS = [
    "undefined_syms_auto.txt",
    "undefined_funcs_auto.txt",
    f"{BASENAME}.ld",
    "linker_script_extra.ld",
]


def find_cross(requested: str | None) -> str:
    if requested:
        return requested
    for prefix in CROSS_CANDIDATES:
        if shutil.which(prefix + "as"):
            return prefix
    return DEFAULT_CROSS


def ninja_path(path: Path | str) -> str:
    """Forward slashes, with ninja's special characters escaped."""
    return str(path).replace("\\", "/").replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def run_split() -> None:
    if not (ROOT / BASE_ROM).is_file():
        subprocess.run(
            [sys.executable, "tools/elf2rom.py", BASE_ELF, BASE_ROM], cwd=ROOT, check=True
        )
    subprocess.run([sys.executable, "-m", "splat", "split", SPLAT_CONFIG], cwd=ROOT, check=True)


def asm_sources() -> list[Path]:
    """Loader ELF sources from splat. asm/xff/ belongs to the XFF modules."""
    return sorted(
        p.relative_to(ROOT)
        for p in (ROOT / "asm").rglob("*.s")
        if (ROOT / "asm" / "xff") not in p.parents
    )


def xff_modules() -> list[str]:
    return [m for m in XFF_MODULES if (ROOT / f"iso/{m}.XFF").is_file()]


def run_xff_split(modules: list[str]) -> None:
    if modules:
        subprocess.run(
            [sys.executable, "tools/xff_split.py", *(f"iso/{m}.XFF" for m in modules)],
            cwd=ROOT,
            check=True,
        )


def object_for(source: Path) -> Path:
    # Matches the paths splat writes into the linker script (o_as_suffix: build/asm/x.o).
    return Path(BUILD_DIR) / source.with_suffix(".o")


def generate(cross: str, sources: list[Path], modules: list[str] | None = None) -> str:
    modules = modules or []
    python = f'"{sys.executable}"'.replace("$", "$$")
    elf = f"{BUILD_DIR}/{BASENAME}.elf"
    rom = f"{BUILD_DIR}/{BASENAME}.rom"
    objects = [ninja_path(object_for(s)) for s in sources]
    ld_scripts = " ".join(f"-T {s}" for s in LD_SCRIPTS)

    lines = [
        "# Generated by configure.py. Do not edit.",
        f"cross = {cross}",
        f"asflags = {ASFLAGS}",
        f"python = {python}",
        "",
        "rule as",
        "  command = ${cross}as $asflags -o $out $in",
        "  description = AS $in",
        "",
        "rule ld",
        f"  command = ${{cross}}ld {LDFLAGS} {ld_scripts} -Map {BUILD_DIR}/{BASENAME}.map"
        " --no-check-sections -o $out",
        "  description = LD $out",
        "",
        "rule flatten",
        "  command = $python tools/elf2rom.py $in $out",
        "  description = FLATTEN $out",
        "",
        "rule check",
        "  command = $python tools/check.py $in",
        "  description = CHECK",
        "",
        "rule xff2elf",
        "  command = $python tools/xff2.py to-elf $in $out",
        "  description = XFF2ELF $in",
        "",
        "rule xffcheck",
        "  command = $python tools/xff_split.py --compare $in",
        "  description = CHECK $in",
        "",
        "rule eecc",
        "  command = $python tools/ee_cc.py $in $out",
        "  description = EECC $in",
        "",
        "rule splice",
        "  command = $python tools/xff_splice.py $module $in --out $outdir",
        "  description = SPLICE $module",
        "",
        "rule configure",
        "  command = $python configure.py --cross $cross",
        "  generator = 1",
        "",
        f"build build.ninja: configure configure.py {SPLAT_CONFIG}",
        "",
    ]
    for source, obj in zip(sources, objects, strict=True):
        lines.append(f"build {obj}: as {ninja_path(source)} | include/macro.inc")
    lines += [
        "",
        f"build {elf}: ld | {' '.join(objects)} {' '.join(LD_SCRIPTS)}",
        f"build {rom}: flatten {elf}",
        f"build {BASE_ROM}: flatten {BASE_ELF}",
        f"build check-elf: check {rom} {BASE_ROM}",
        "",
    ]

    # XFF modules: assemble the split and compare sections + relocations with
    # the original object converted from the disc's XFF.
    checks = ["check-elf"]
    for m in modules:
        original = f"{BUILD_DIR}/xff/{m}.o"
        rebuilt = f"{BUILD_DIR}/xff/{m}/{m}.o"
        asm_dir = f"asm/xff/{m}"
        asm_files = sorted(p.name for p in (ROOT / asm_dir).glob("*.s"))
        deps = " ".join(f"{asm_dir}/{name}" for name in asm_files)
        lines.append(f"build {original}: xff2elf iso/{m}.XFF")

        # Decompiled C (src/xff/<MODULE>/*.c) replaces its functions' assembly.
        c_files = sorted((ROOT / "src" / "xff" / m).glob("*.c"))
        if c_files:
            c_objects = []
            for c in c_files:
                obj = f"{BUILD_DIR}/src/xff/{m}/{c.stem}.o"
                lines.append(f"build {obj}: eecc {ninja_path(c.relative_to(ROOT))}")
                c_objects.append(obj)
            spliced = f"{BUILD_DIR}/xff/{m}/spliced"
            extra = " ".join(f"{spliced}/{name}" for name in asm_files if name != f"{m}.s")
            inputs = " ".join(c_objects)
            lines += [
                f"build {spliced}/{m}.s | {extra}: splice {inputs}"
                f" | {original} tools/xff_splice.py {deps}",
                f"  module = {m}",
                f"  outdir = {spliced}",
            ]
            asm_dir, deps = spliced, extra

        lines += [
            f"build {rebuilt}: as {asm_dir}/{m}.s | include/xff_macro.inc {deps}",
            f"  asflags = $asflags -I {asm_dir}",
            f"build check-{m}: xffcheck {original} {rebuilt}",
        ]
        checks.append(f"check-{m}")
    lines += [
        "",
        f"build check: phony {' '.join(checks)}",
        "",
        f"default {rom} {' '.join(f'{BUILD_DIR}/xff/{m}/{m}.o' for m in modules)}".rstrip(),
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--split", action="store_true", help="re-run splat before generating")
    parser.add_argument("--cross", default=os.environ.get("SOTC_CROSS"), help="binutils prefix")
    args = parser.parse_args(argv)

    if not (ROOT / BASE_ELF).is_file():
        print(f"Missing {BASE_ELF}. Copy it from your own disc first.", file=sys.stderr)
        return 1
    if args.split or not (ROOT / "asm" / "cod").is_dir():
        run_split()
    modules = xff_modules()
    run_xff_split([m for m in modules if args.split or not (ROOT / f"asm/xff/{m}/{m}.s").is_file()])

    cross = find_cross(args.cross)
    if not shutil.which(cross + "as"):
        print(f"warning: {cross}as not found on PATH; `ninja` will fail until it's installed.")

    (ROOT / "build.ninja").write_text(generate(cross, asm_sources(), modules), encoding="utf-8")
    print(f"Wrote build.ninja (cross = {cross})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
